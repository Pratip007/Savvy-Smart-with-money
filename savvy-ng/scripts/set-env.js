const fs = require('fs');
const path = require('path');

const envFile = path.resolve(__dirname, '../.env');
if (!fs.existsSync(envFile)) {
  console.error('ERROR: .env file not found.');
  process.exit(1);
}

const env = {};
fs.readFileSync(envFile, 'utf8').split('\n').forEach(line => {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) return;
  const eq = trimmed.indexOf('=');
  if (eq === -1) return;
  const key = trimmed.slice(0, eq).trim();
  const val = trimmed.slice(eq + 1).trim().replace(/^['"]|['"]$/g, '');
  env[key] = val;
});

const clientId = env.GOOGLE_CLIENT_ID;
if (!clientId) {
  console.error('ERROR: GOOGLE_CLIENT_ID missing from .env');
  process.exit(1);
}

const outFile = path.resolve(__dirname, '../src/environments/environment.ts');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile,
  `// Auto-generated by scripts/set-env.js — do not edit or commit\nexport const environment = {\n  production: false,\n  googleClientId: '${clientId}',\n};\n`,
  'utf8'
);
console.log('environment.ts generated from .env');
