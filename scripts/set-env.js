const fs = require('fs');
const path = require('path');

// Try process.env first (Vercel / CI), then fall back to .env file (local dev)
let clientId = process.env.GOOGLE_CLIENT_ID;

if (!clientId) {
  const envFile = path.resolve(__dirname, '../.env');
  if (!fs.existsSync(envFile)) {
    console.error('ERROR: GOOGLE_CLIENT_ID env var not set and .env file not found.');
    process.exit(1);
  }
  const env = {};
  fs.readFileSync(envFile, 'utf8').split('\n').forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const eq = trimmed.indexOf('=');
    if (eq === -1) return;
    const key = trimmed.slice(0, eq).trim();
    const val = trimmed.slice(eq + 1).trim().replace(/^['"]|['"]$/g, '');
    env[key] = val;
  });
  clientId = env.GOOGLE_CLIENT_ID;
}

if (!clientId) {
  console.error('ERROR: GOOGLE_CLIENT_ID missing from environment and .env');
  process.exit(1);
}

const isProduction = process.env.NODE_ENV === 'production';

const outFile = path.resolve(__dirname, '../src/environments/environment.ts');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile,
  `// Auto-generated by scripts/set-env.js — do not edit or commit\nexport const environment = {\n  production: ${isProduction},\n  googleClientId: '${clientId}',\n};\n`,
  'utf8'
);
console.log('environment.ts generated');
